def add_h1(doc: Document, num: int, title: str) -> None:
    doc.add_heading(f"{num}. {title}", level=1)


def add_p(doc: Document, text: str, *, bold_prefix: str | None = None, no_indent=False, italic=False) -> None:
    p = doc.add_paragraph()
    if no_indent:
        p.paragraph_format.first_line_indent = Cm(0)
    if bold_prefix and text.startswith(bold_prefix):
        r1 = p.add_run(bold_prefix)
        set_run_font(r1, 12, bold=True)
        r2 = p.add_run(text[len(bold_prefix):])
        set_run_font(r2, 12, italic=italic)
    else:
        r = p.add_run(text)
        set_run_font(r, 12, italic=italic)


def add_bullets(doc: Document, items: Iterable[str]) -> None:
    for item in items:
        p = doc.add_paragraph(style="List Bullet")
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.left_indent = Cm(0.75)
        r = p.add_run(item)
        set_run_font(r, 12)


def add_numbered(doc: Document, items: Iterable[str]) -> None:
    for item in items:
        p = doc.add_paragraph(style="List Number")
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.left_indent = Cm(0.75)
        r = p.add_run(item)
        set_run_font(r, 12)


def add_table(doc: Document, headers: Sequence[str], rows: Sequence[Sequence[object]], widths: Sequence[float] | None = None):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    hdr = table.rows[0].cells
    for i, header in enumerate(headers):
        hdr[i].text = str(header)
        set_cell_shading(hdr[i], "D9EAF7")
        for p in hdr[i].paragraphs:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            for run in p.runs:
                run.bold = True
    for row_values in rows:
        cells = table.add_row().cells
        for i, value in enumerate(row_values):
            cells[i].text = str(value)
    if widths:
        for row in table.rows:
            for i, width in enumerate(widths):
                row.cells[i].width = Cm(width)
    set_repeat_table_header_and_layout(table)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return table


